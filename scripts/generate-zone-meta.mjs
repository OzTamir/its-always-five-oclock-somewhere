// Regenerates src/lib/zoneMeta.ts from the system IANA zone.tab.
// Usage: node scripts/generate-zone-meta.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const ZONE_TAB = '/usr/share/zoneinfo/zone.tab'

/** Parse an ISO 6709 half ("+4230" / "-032342") into decimal degrees. */
function parseCoordinate(raw) {
  const sign = raw[0] === '-' ? -1 : 1
  const digits = raw.slice(1)
  let degrees, minutes, seconds
  if (digits.length <= 3) {
    // DD or DDD
    ;[degrees, minutes, seconds] = [Number(digits), 0, 0]
  } else if (digits.length <= 5) {
    // DDMM or DDDMM
    degrees = Number(digits.slice(0, -2))
    minutes = Number(digits.slice(-2))
    seconds = 0
  } else {
    // DDMMSS or DDDMMSS
    degrees = Number(digits.slice(0, -4))
    minutes = Number(digits.slice(-4, -2))
    seconds = Number(digits.slice(-2))
  }
  return sign * (degrees + minutes / 60 + seconds / 3600)
}

const entries = []
for (const line of readFileSync(ZONE_TAB, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue
  const [country, coords, zone] = line.split('\t')
  if (!country || !coords || !zone) continue
  const match = coords.match(/^([+-]\d+)([+-]\d+)$/)
  if (!match) continue
  const lat = parseCoordinate(match[1])
  const lon = parseCoordinate(match[2])
  entries.push(
    `  '${zone}': ['${country}', ${lat.toFixed(2)}, ${lon.toFixed(2)}],`,
  )
}

const output = `// Generated by scripts/generate-zone-meta.mjs from IANA zone.tab.
// Do not edit by hand — rerun the script instead.

/** [ISO 3166 country code, latitude, longitude] */
export type ZoneMeta = [string, number, number]

export const ZONE_META: Record<string, ZoneMeta> = {
${entries.join('\n')}
}
`

writeFileSync(new URL('../src/lib/zoneMeta.ts', import.meta.url), output)
console.log(`Wrote ${entries.length} zones`)
